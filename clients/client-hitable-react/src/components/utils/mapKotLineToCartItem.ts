import type { ICartItem } from '@/components/store/useCartStore';
import type { OrderData } from '@/components/types/hiClientzData';
import type { DishType } from '@hi/db-models/src/validators';

/**
 * Maps a KOT line item to a Cart Item format
 * Preserves all original item details: dish, portion, extras, quantity, instructions
 */
export function mapKotLineToCartItem(kotLineItem: OrderData['cart'][0]): ICartItem | null {
  // Skip deleted items
  if (kotLineItem.isDeleted) {
    return null;
  }

  // Extract dish information
  // Note: KOT items may have minimal dish data, we need to preserve what we have
  const dish = kotLineItem.dish as any; // Using any since DishType might have more fields at runtime
  
  // If dish doesn't have _id, we can't add it (would be invalid)
  if (!dish?._id && !kotLineItem.dish?._id) {
    // Try to find _id from the item itself if available
    const dishId = (kotLineItem as any).dishId || (kotLineItem as any).dish?._id;
    if (!dishId) {
      console.warn('Cannot map KOT item: missing dish _id', kotLineItem);
      return null;
    }
    dish._id = dishId;
  }

  // Map portion
  let portion: { _id: number; name: string; price: number } | null = null;
  if (kotLineItem.portion) {
    // Try to get _id from portion, or use a numeric ID if not available
    const portionId = (kotLineItem.portion as any)?._id || (kotLineItem.portion as any)?.id;
    portion = {
      _id: portionId ? (typeof portionId === 'number' ? portionId : parseInt(portionId, 10) || 0) : 0,
      name: kotLineItem.portion.name,
      price: kotLineItem.portion.price,
    };
  }

  // Map extras/addons
  const extras: Array<{ id: string; name: string; quantity: number; price: number }> = [];
  if (kotLineItem.extras && Array.isArray(kotLineItem.extras)) {
    for (const extra of kotLineItem.extras) {
      extras.push({
        id: extra.id || (extra as any)._id || '',
        name: extra.name || '',
        quantity: extra.quantity || 0,
        price: extra.price || 0,
      });
    }
  }

  // Build full dish object - preserve all fields from original
  // This ensures we maintain dish metadata like dishTypes, categoryIds, etc.
  const fullDish: DishType = {
    ...dish,
    _id: dish._id || (kotLineItem as any).dishId || '',
    name: dish.name || '',
    price: dish.price || 0,
    // Preserve instruction if it exists on the dish
    instruction: (dish as any).instruction || '',
  };

  // Add instruction to dish if present (some systems store it on the item)
  const instruction = (kotLineItem as any).instruction || (kotLineItem.dish as any)?.instruction || '';
  if (instruction) {
    fullDish.instruction = instruction;
  }

  // Create cart item
  const cartItem: ICartItem = {
    id: '', // Will be generated by addToCart
    dish: fullDish,
    portion,
    extras,
    quantity: kotLineItem.quantity || 1,
  };

  // Generate a unique ID that includes instruction to prevent incorrect merging
  // This ensures items with same dish/portion/extras but different instructions stay separate
  const sortedExtras = [...extras]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((e) => `${e.id}:${e.quantity}`)
    .join('|');
  const instructionHash = instruction ? `_inst_${instruction.slice(0, 20).replace(/\s/g, '_')}` : '';
  cartItem.id = `${fullDish._id}_${portion?._id || 'no_portion'}_${sortedExtras || 'no_extras'}${instructionHash}`;

  return cartItem;
}
