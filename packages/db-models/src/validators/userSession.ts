import { z } from "zod";
import { ObjectIdSchema } from "./common";

export const userSessionSchema = z.object({
  businessId: ObjectIdSchema,
  pin: z.string().min(10).max(10),
  tableName: z.string().min(1).max(20),
  hiCode: z.string().min(1).max(20).optional(),
  customerName: z.string().min(1).max(50),
  phoneNumbers: z.array(z.string().min(10).max(10)),
  billGeneratedBy: z.string().min(1).max(50).optional(),
  serviceCharge: z.coerce.number().optional().default(0),
  settleType: z.string().min(1).max(50).optional(),
  performedBy: z.string().min(1).max(50).optional(),
  isTransfer: z.boolean().default(false).optional(),
  transferTableTo: z.string().max(50).optional(),
  transferTableFrom: z.string().max(50).optional(),
  transferBy: ObjectIdSchema.optional(),
  transferType: z.enum(["TABLE", "ITEM"]).optional(),
  date: z.coerce.number().optional(),

  total: z.coerce.number().optional().default(0),
  subTotal: z.coerce.number().optional().default(0),
  gst: z.coerce.number().optional().default(0),

  discount: z.coerce.number().optional().default(0),
  tips: z.coerce.number().optional().default(0),
  claimedCoins: z.coerce.number().optional().default(0),
  couponId: z.string().max(50).optional(),
  couponDiscount: z.coerce.number().optional().default(0),
  isDiscountApplied: z.boolean().default(false).optional(),
  reasonOfDiscount: z.string().max(100).optional(),
  serviceChargeAppliedBy: ObjectIdSchema.optional(),
  serviceChargeRemovedBy: ObjectIdSchema.optional(),
  discountAppliedBy: ObjectIdSchema.optional(),
  discountRemovedBy: ObjectIdSchema.optional(),
  reasonOfServiceCharge: z.string().max(100).optional(),
  otherTax: z.coerce.number().optional().default(0),
  discountAppliedOn: z.enum(["ON_BILL", "ON_DISH"]).optional(),
  gstPercentage: z.coerce.number().optional().default(5),
  serviceChargePercentage: z.coerce.number().optional().default(0),
  newDishGst: z.coerce.number().optional().default(0),
  isServiceChargeRemoved: z.boolean().optional().default(false),
  customerIds: z.array(ObjectIdSchema).optional(),
  items: z.array(z.object({})).optional(),
  isUserRegistered: z.boolean().optional().default(false),
  billRequest: z.boolean().optional().default(false),
  billPrintCount: z.coerce.number().optional().default(0),
  dishIds: z.array(z.string()).optional(),
  billInvoiceNumber: z.coerce.number().optional().default(0),
  isSplit: z.boolean().optional().default(false),
  _id: z.string().optional(),
  variantsCounts: z.number().optional().default(0),
  discountPercentage: z.coerce.number().optional().default(0),
  splitType: z.enum(["PORTION", "ITEM"]).optional().default("PORTION"),
  totalGst: z.coerce.number().optional().default(0),
  coinPercentage: z.coerce.number().optional().default(0),
  couponPercentage: z.coerce.number().optional().default(0),
  itemIds: z.array(z.string()).optional(),
  itemGst: z.coerce.number().optional().default(0),
  itemGstAfterDiscount: z.coerce.number().optional().default(0),
  isMerge: z.boolean().optional().default(false),
  mergeTableNames: z.array(z.string()).optional().default([]),
  coinAppliedBy: ObjectIdSchema.optional(),
  isOrderInitiated: z.boolean().default(false),
  billInvoice: z.coerce.number().optional().default(0),
  isBillInvoiced: z.boolean().optional().default(false),
  paxCount: z.coerce.number().optional().default(0),
  billingUserId: ObjectIdSchema.optional(),
  roundOffType: z.coerce.number().optional().default(0),
  roundOffAmount: z.coerce.number().optional().default(0),
});

export type UserSessionSchemaType = z.infer<typeof userSessionSchema>;
