import { z } from 'zod';

export const Item = z.object({
  name: z.string(),
  quantity: z.number(),
  amount: z.number(),
  portions: z.any(),
  extras: z.any(),
  comments: z.string(),
  category: z.string(),
});

export const SwiggyBillObj = z.object({
  totalItems: z.number(),
  subTotal: z.number(),
  packingCharges: z.number(),
  RxPayableGST: z.number(),
  swiggyPayableGST: z.number(),
  discount: z.number(),
  totalPrice: z.number(),
});

